using System;
using System.Threading;
using System.Threading.Tasks;
using EquipmentBorrowing.Application.Interfaces;
using EquipmentBorrowing.Domain;

namespace EquipmentBorrowing.Application.Services;

public class BorrowEquipmentService
{
    private readonly IStudentRepository _studentRepository;
    private readonly IEquipmentRepository _equipmentRepository;
    private readonly IBorrowingRepository _borrowingRepository;
    public const int MaxActiveBorrowings = 3;

    public BorrowEquipmentService(
        IStudentRepository studentRepository,
        IEquipmentRepository equipmentRepository,
        IBorrowingRepository borrowingRepository)
    {
        _studentRepository = studentRepository;
        _equipmentRepository = equipmentRepository;
        _borrowingRepository = borrowingRepository;
    }

    /// <summary>
    /// Executes the Borrow Equipment use case (UC-03).
    /// </summary>
    public async Task<BorrowResult> BorrowAsync(
        int studentId,
        int equipmentId,
        DateTime? expectedReturnDate = null,
        CancellationToken cancellationToken = default)
    {
        var checkoutDate = DateTime.Now;
        var returnDate = expectedReturnDate ?? checkoutDate.AddDays(7);

        // BR-11: Expected return date must be later than checkout date
        if (returnDate <= checkoutDate)
            return BorrowResult.Fail("Expected return date must be later than the checkout date.");

        var student = await _studentRepository.GetByIdAsync(studentId, cancellationToken);
        if (student is null)
            return BorrowResult.Fail("Student does not exist.");

        // BR-08: Student must be eligible to borrow
        if (!student.IsAllowedToBorrow)
            return BorrowResult.Fail($"Student '{student.Name}' is restricted from borrowing equipment.");

        var equipment = await _equipmentRepository.GetByIdAsync(equipmentId, cancellationToken);
        if (equipment is null)
            return BorrowResult.Fail("Equipment does not exist.");

        // BR-10: Equipment must be available
        if (!equipment.IsAvailable)
            return BorrowResult.Fail($"Equipment '{equipment.Name}' is currently unavailable.");

        // BR-09: Active loan limit
        var activeCount = await _borrowingRepository.CountActiveBorrowingsAsync(studentId, cancellationToken);
        if (activeCount >= MaxActiveBorrowings)
            return BorrowResult.Fail($"Student has reached the maximum limit of {MaxActiveBorrowings} active borrowings.");

        // Create borrowing with Id = 0 (identity generated by PostgreSQL)
        var borrowing = new Borrowing(
            id: 0,
            studentId: studentId,
            equipmentId: equipmentId,
            dateBorrowed: checkoutDate,
            expectedReturnDate: returnDate);

        equipment.MarkAsBorrowed();
        await _equipmentRepository.UpdateAsync(equipment, cancellationToken);
        await _borrowingRepository.AddAsync(borrowing, cancellationToken);

        return BorrowResult.Success(borrowing);
    }
}

public class BorrowResult
{
    public bool IsSuccess { get; }
    public string? ErrorMessage { get; }
    public Borrowing? Borrowing { get; }

    private BorrowResult(bool isSuccess, string? errorMessage, Borrowing? borrowing)
    {
        IsSuccess = isSuccess;
        ErrorMessage = errorMessage;
        Borrowing = borrowing;
    }

    public static BorrowResult Success(Borrowing borrowing) => new(true, null, borrowing);
    public static BorrowResult Fail(string errorMessage) => new(false, errorMessage, null);
}